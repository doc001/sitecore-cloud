/**
 * Process downloads in batches using Sitecore GraphQL API
 */
async function processDownloads(courseOutlines, startIndex = 0) {
  const stats = {
    processed: 0,
    downloaded: 0,
    failed: 0,
    skipped: 0
  };
  
  // Filter courses that have File Path field (media library path)
  const coursesWithFiles = courseOutlines.filter(course => {
    const filePathField = course.fields["File Path"];
    return filePathField && filePathField.value && filePathField.value.trim();
  });
  
  console.log(`📊 Found ${coursesWithFiles.length} courses with File Path field out of ${courseOutlines.length} total`);
  
  // Log some examples of File Path values for debugging
  console.log("🔍 Sample File Paths:");
  coursesWithFiles.slice(0, 3).forEach((course, index) => {
    const filePath = course.fields["File Path"]?.value;
    console.log(`  ${index + 1}. ${course.name}: ${filePath}`);
  });
  
  const totalItems = coursesWithFiles.length;
  
  if (SKIP_DOWNLOAD) {
    console.log("⏭️  Skipping PDF downloads as requested");
    return stats;
  }
  
  console.log(`🔄 Processing ${totalItems - startIndex} PDF downloads in batches of ${BATCH_SIZE}...`);
  console.log(`🛑 Break on error: ${!NO_BREAK_ON_ERROR ? 'YES' : 'NO'}`);

  for (let i = startIndex; i < totalItems; i += BATCH_SIZE) {
    const batch = coursesWithFiles.slice(i, Math.min(i + BATCH_SIZE, totalItems));
    const batchNumber = Math.floor(i / BATCH_SIZE) + 1;
    const totalBatches = Math.ceil((totalItems - startIndex) / BATCH_SIZE);
    
    console.log(`\n📦 Processing batch ${batchNumber}/${totalBatches} (items ${i + 1}-${Math.min(i + BATCH_SIZE, totalItems)} of ${totalItems})`);

    // Process batch sequentially for GraphQL API calls (to avoid overwhelming the API)
    for (const course of batch) {
      const filename = generateSafeFilename(course);
      const filePath = path.resolve(PDF_OUTPUT_DIR, filename);
      
      try {
        // Check if file already exists
        await fs.access(filePath);
        console.log(`  ⏭️  Skipping (already exists): ${filename}`);
        stats.skipped++;
        continue;
      } catch {
        // File doesn't exist, proceed with download
      }
      
      try {
        const result = await downloadPDF(course, filePath);
        if (result.success) {
          stats.downloaded++;
        } else {
          stats.failed++;
        }
      } catch (error) {
        console.error(`  ❌ FATAL ERROR processing ${course.name}: ${error.message}`);
        stats.failed++;
        
        if (!NO_BREAK_ON_ERROR) {
          // Save progress before stopping
          await saveProgress(i + stats.processed + 1, totalItems, stats.downloaded, stats.failed);
          throw error;
        }
      }
      
      stats.processed++;
      
      // Small delay between individual downloads
      await new Promise(resolve => setTimeout(resolve, 500));
    }
    
    // Save progress after each successful batch
    await saveProgress(i + batch.length, totalItems, stats.downloaded, stats.failed);
    console.log(`   ✅ Batch ${batchNumber} completed - Downloaded: ${stats.downloaded}, Failed: ${stats.failed}, Skipped: ${stats.skipped}`);
    
    // Delay between batches
    await new Promise(resolve => setTimeout(resolve, 1000));
  }

  return stats;
}// File: ./scripts/downloadCoursePDFs.mjs
