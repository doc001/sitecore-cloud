/**
 * Helper to perform a GraphQL request to Sitecore XM Cloud.
 */
async function runGraphQL(query, variables = {}) {
  const headers = {
    "Content-Type": "application/json",
    "sc_apikey": API_KEY,
  };

  try {
    const response = await fetch(GRAPHQL_ENDPOINT, {
      method: "POST",
      headers,
      body: JSON.stringify({ query, variables }),
    });

    if (!response.ok) {
      const text = await response.text();
      throw new Error(`GraphQL request failed: ${response.status} ${text}`);
    }

    const json = await response.json();
    if (json.errors) {
      throw new Error(`GraphQL errors: ${JSON.stringify(json.errors, null, 2)}`);
    }
    return json.data;
  } catch (error) {
    console.error("❌ GraphQL Request Error:", error.message);
    throw error;
  }
}

/**
 * Get media item details and download URL from Sitecore using GraphQL
 */
async function getMediaItemDetails(mediaPath) {
  // Clean the media path for GraphQL query
  let cleanPath = mediaPath;
  if (cleanPath.startsWith('/sitecore/media library')) {
    cleanPath = cleanPath.replace('/sitecore/media library', '');
  }
  if (!cleanPath.startsWith('/sitecore/media library')) {
    cleanPath = '/sitecore/media library' + cleanPath;
  }

  const MEDIA_QUERY = `
    query GetMediaItem($path: String!) {
      item(path: $path, language: "en") {
        id
        name
        path
        fields {
          name
          value
        }
        ... on MediaItem {
          blob
          size
          mimeType
          extension
        }
      }
    }
  `;

  try {
    console.log(`  🔍 Querying media item at path: ${cleanPath}`);
    const data = await runGraphQL(MEDIA_QUERY, { path: cleanPath });
    
    if (!data.item) {
      throw new Error(`Media item not found at path: ${cleanPath}`);
    }

    return data.item;
  } catch (error) {
    console.error(`  ❌ Failed to get media item details: ${error.message}`);
    throw error;
  }
}

/**
 * Download media item blob data using GraphQL
 */
async function downloadMediaBlob(mediaItem, filePath, courseData) {
  try {
    console.log(`  📥 Downloading media blob for: ${courseData.name}`);
    console.log(`  📊 Media details - Size: ${mediaItem.size}, Type: ${mediaItem.mimeType}`);
    
    if (!mediaItem.blob) {
      throw new Error("No blob data available for media item");
    }
    
    // The blob field should contain base64 encoded data or a download URL
    // This depends on your Sitecore XM Cloud configuration
    if (typeof mediaItem.blob === 'string' && mediaItem.blob.startsWith('http')) {
      // If blob contains a URL, download from that URL with authentication
      return await downloadFromUrl(mediaItem.blob, filePath, courseData);
    } else if (typeof mediaItem.blob === 'string') {
      // If blob contains base64 data, decode and save
      return await saveBase64Data(mediaItem.blob, filePath, courseData);
    } else {
      throw new Error("Unsupported blob data format");
    }
    
  } catch (error) {
    console.error(`  ❌ Failed to download media blob: ${error.message}`);
    throw error;
  }
}

/**
 * Download from authenticated URL
 */
async function downloadFromUrl(url, filePath, courseData) {
  const headers = {
    "sc_apikey": API_KEY,
  };

  const response = await fetch(url, { headers });
  
  if (!response.ok) {
    throw new Error(`HTTP ${response.status}: ${response.statusText}`);
  }

  const fileStream = createWriteStream(filePath);
  await pipeline(response.body, fileStream);
  
  console.log(`  ✅ Downloaded from URL: ${path.basename(filePath)}`);
  return { success: true, filePath };
}

/**
 * Save base64 encoded data to file
 */
async function saveBase64Data(base64Data, filePath, courseData) {
  // Remove data URL prefix if present
  const cleanBase64 = base64Data.replace(/^data:[^;]+;base64,/, '');
  
  const buffer = Buffer.from(cleanBase64, 'base64');
  await fs.writeFile(filePath, buffer);
  
  console.log(`  ✅ Saved base64 data: ${path.basename(filePath)}`);
  return { success: true, filePath };
}

/**
 * Generate a safe filename from course data
 */
function generateSafeFilename(courseData) {
  const academicYear = courseData.fields["Academic Year"]?.value || "Unknown";
  const courseCode = courseData.fields["Course Code"]?.value || "Unknown";
  const courseName = courseData.fields["CourseName"]?.value || "Unknown";
  
  // Create a safe filename
  const safeName = `${academicYear}_${courseCode}_${courseName}`
    .replace(/[^a-zA-Z0-9\-_]/g, '_')
    .replace(/_{2,}/g, '_')
    .substring(0, 100); // Limit filename length
  
  return `${safeName}.pdf`;
}

/**
 * Load course outlines data from JSON file
 */
async function loadCourseOutlines() {
  try {
    const filePath = path.resolve(INPUT_FILE);
    const data = await fs.readFile(filePath, "utf-8");
    return JSON.parse(data);
  } catch (error) {
    throw new Error(`Failed to load course outlines data: ${error.message}`);
  }
}

/**
 * Save progress to resume downloads if interrupted
 */
async function saveProgress(processedCount, totalCount, downloadedCount, failedCount) {
  const progressData = {
    processedCount,
    totalCount,
    downloadedCount,
    failedCount,
    timestamp: new Date().toISOString(),
  };
  
  const progressPath = path.resolve(JSON_OUTPUT_DIR, PROGRESS_FILE);
  await fs.writeFile(progressPath, JSON.stringify(progressData, null, 2), "utf-8");
}

/**
 * Download a single PDF file using Sitecore GraphQL API
 */
async function downloadPDF(courseData, filePath, retryCount = 0) {
  try {
    console.log(`  📥 Processing: ${courseData.name}`);
    
    // Get the File Path field value (media library path)
    const filePathField = courseData.fields["File Path"];
    if (!filePathField || !filePathField.value) {
      throw new Error("No File Path field found");
    }
    
    const mediaPath = filePathField.value;
    console.log(`  📁 Media path: ${mediaPath}`);
    
    // Get media item details from Sitecore
    const mediaItem = await getMediaItemDetails(mediaPath);
    
    // Download the media blob
    const result = await downloadMediaBlob(mediaItem, filePath, courseData);
    
    return result;
    
  } catch (error) {
    console.error(`  ❌ Download failed: ${error.message}`);
    
    if (retryCount < MAX_RETRIES) {
      console.log(`  🔄 Retrying (${retryCount + 1}/${MAX_RETRIES})...`);
      await new Promise(resolve => setTimeout(resolve, RETRY_DELAY));
      return downloadPDF(courseData, filePath, retryCount + 1);
    }
    
    if (!NO_BREAK_ON_ERROR) {
      throw new Error(`Failed to download ${courseData.name} after ${MAX_RETRIES} attempts: ${error.message}`);
    }
    
    return { success: false, error: error.message };
  }
}

/**
 * Ensure a directory exists (create if missing).
 */
async function ensureDir(dirPath) {
  try {
    await fs.access(dirPath);
  } catch {
    await fs.mkdir(dirPath, { recursive: true });
    console.log(`📁 Created directory: ${dirPath}`);
  }
}

/**
 * Load progress to resume downloads
 */
async function loadProgress() {
  try {
    const progressPath = path.resolve(JSON_OUTPUT_DIR, PROGRESS_FILE);
    const progressData = await fs.readFile(progressPath, "utf-8");
    return JSON.parse(progressData);
  } catch {
    return null; // No progress file exists
  }
}

/**
 * Filter courses for current offerings
 */
function filterCurrentCourses(courseOutlines) {
  const currentCourses = [];
  
  for (const course of courseOutlines) {
    const effectiveTermEnd = course.fields["EffectiveTermEnd"]?.value;
    
    // Check if EffectiveTermEnd includes "Current"
    if (effectiveTermEnd && effectiveTermEnd.includes("Current")) {
      // Extract only the required fields
      const currentCourse = {
        id: course.id,
        name: course.name,
        "Academic Year": course.fields["Academic Year"]?.value || null,
        "EffectiveTermEnd": course.fields["EffectiveTermEnd"]?.value || null,
        "Course Code": course.fields["Course Code"]?.value || null,
        "CourseName": course.fields["CourseName"]?.value || null,
        "EffectiveStartTerm": course.fields["EffectiveStartTerm"]?.value || null,
      };
      
      currentCourses.push(currentCourse);
    }
  }
  
  return currentCourses;
}

