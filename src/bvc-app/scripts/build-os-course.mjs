// scripts/build-os-course.mjs
// Bundles + minifies the Webflow-embedded assets:
//   src/js/os-course/index.js     -> public/js/os-course.js      (self-contained IIFE)
//   src/css/os-course.css         -> public/css/os-course.css    (minified)
//   src/js/checkout/index.js      -> public/js/checkout.js        (self-contained IIFE)
//   src/js/ee-course/index.js     -> public/js/ee-course.js       (self-contained IIFE)
//   src/js/checkout-cart/index.js -> public/js/checkout-cart.js   (self-contained IIFE)
//   src/css/checkout-cart.css     -> public/css/checkout-cart.css (minified)
//   src/js/program-requirements/index.js -> public/js/program-requirements.js  (self-contained IIFE)
//   src/css/program-requirements.css     -> public/css/program-requirements.css (minified)
//   src/js/program-tuition/index.js -> public/js/program-tuition.js  (self-contained IIFE)
//   src/css/program-tuition.css     -> public/css/program-tuition.css (minified)
//   src/js/ee-listing/index.js    -> public/js/ee-listing.js     (self-contained IIFE)
//
//   node scripts/build-os-course.mjs            one-off minified build
//   node scripts/build-os-course.mjs --watch    rebuild all on every save
//
// Output is plain static assets so they can be dropped onto any page —
// including Webflow — via <script src> / <link rel="stylesheet">.
import { fileURLToPath } from 'url';
import path from 'path';
import * as esbuild from 'esbuild';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const GENERATED = 'generated by build-os-course.mjs. DO NOT EDIT. Edit the matching file under src/.';

// PROD builds minify, strip comments, and drop console/debugger statements.
// UAT/DEV builds keep them for debugging. Trigger a prod build with the --prod
// flag (e.g. `js:build:prod`) or by setting STRIP_DEBUG=true in the environment
// (e.g. only on the PROD Vercel project).
const isProd = process.argv.includes('--prod') || process.env.STRIP_DEBUG === 'true';

// The data origin controls where the Webflow embeds fetch JSON from at runtime.
// Set by pipeline.mjs from the deploy target's alias (e.g. bvc-app-uat.vercel.app
// for UAT, bvc-app.vercel.app for PROD). Falls back to bvc-app-uat.vercel.app so
// a standalone `npm run js:build` without the pipeline defaults to UAT.
const dataOrigin = process.env.BVC_DATA_ORIGIN || 'https://bvc-app-uat.vercel.app';
const apiOrigin = process.env.BVC_API_ORIGIN || 'https://bvc-uat-api-proxy.vercel.app';

/** @type {esbuild.BuildOptions[]} */
