// scripts/build-os-course.mjs
// Bundles + minifies the Webflow-embedded assets:
//   src/js/os-course/index.js     -> public/js/os-course.js      (self-contained IIFE)
//   src/css/os-course.css         -> public/css/os-course.css    (minified)
//   src/js/checkout/index.js      -> public/js/checkout.js        (self-contained IIFE)
//   src/js/ee-course/index.js     -> public/js/ee-course.js       (self-contained IIFE)
//   src/js/checkout-cart/index.js -> public/js/checkout-cart.js   (self-contained IIFE)
//   src/css/checkout-cart.css     -> public/css/checkout-cart.css (minified)
//   src/js/program-requirements/index.js -> public/js/program-requirements.js  (self-contained IIFE)
//   src/css/program-requirements.css     -> public/css/program-requirements.css (minified)
//
//   node scripts/build-os-course.mjs            one-off minified build
//   node scripts/build-os-course.mjs --watch    rebuild all on every save
//
// Output is plain static assets so they can be dropped onto any page —
// including Webflow — via <script src> / <link rel="stylesheet">.
import { fileURLToPath } from 'url';
import path from 'path';
import * as esbuild from 'esbuild';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const GENERATED = 'generated by build-os-course.mjs. DO NOT EDIT. Edit the matching file under src/.';

// PROD builds minify, strip comments, and drop console/debugger statements.
// UAT/DEV builds keep them for debugging. Trigger a prod build with the --prod
// flag (e.g. `js:build:prod`) or by setting STRIP_DEBUG=true in the environment
// (e.g. only on the PROD Vercel project).
const isProd = process.argv.includes('--prod') || process.env.STRIP_DEBUG === 'true';

/** @type {esbuild.BuildOptions[]} */
const targets = [
  {
    entryPoints: [path.join(root, 'src/js/os-course/index.js')],
    outfile: path.join(root, 'public/js/os-course.js'),
    bundle: true,
    minify: isProd,
    format: 'iife',
    target: ['es2017'],
    legalComments: 'none',
    drop: isProd ? ['console', 'debugger'] : [],
    banner: { js: `/* os-course.js — ${GENERATED} */` },
  },
  {
    entryPoints: [path.join(root, 'src/css/os-course.css')],
    outfile: path.join(root, 'public/css/os-course.css'),
    bundle: true,
    minify: isProd,
    legalComments: 'none',
    banner: { css: `/* os-course.css — ${GENERATED} */` },
  },
  {
    entryPoints: [path.join(root, 'src/js/checkout/index.js')],
    outfile: path.join(root, 'public/js/checkout.js'),
    bundle: true,
    minify: isProd,
    format: 'iife',
    target: ['es2017'],
    legalComments: 'none',
    drop: isProd ? ['console', 'debugger'] : [],
    banner: { js: `/* checkout.js — ${GENERATED} */` },
  },
  {
    entryPoints: [path.join(root, 'src/js/ee-course/index.js')],
    outfile: path.join(root, 'public/js/ee-course.js'),
    bundle: true,
    minify: isProd,
    format: 'iife',
    target: ['es2017'],
    legalComments: 'none',
    drop: isProd ? ['console', 'debugger'] : [],
    banner: { js: `/* ee-course.js — ${GENERATED} */` },
  },
  {
    entryPoints: [path.join(root, 'src/js/checkout-cart/index.js')],
    outfile: path.join(root, 'public/js/checkout-cart.js'),
    bundle: true,
    minify: isProd,
    format: 'iife',
    target: ['es2017'],
    legalComments: 'none',
    drop: isProd ? ['console', 'debugger'] : [],
    banner: { js: `/* checkout-cart.js — ${GENERATED} */` },
  },
  {
    entryPoints: [path.join(root, 'src/css/checkout-cart.css')],
    outfile: path.join(root, 'public/css/checkout-cart.css'),
    bundle: true,
    minify: isProd,
    legalComments: 'none',
    banner: { css: `/* checkout-cart.css — ${GENERATED} */` },
  },
  {
    entryPoints: [path.join(root, 'src/js/program-requirements/index.js')],
    outfile: path.join(root, 'public/js/program-requirements.js'),
    bundle: true,
    minify: isProd,
    format: 'iife',
    target: ['es2017'],
    legalComments: 'none',
    drop: isProd ? ['console', 'debugger'] : [],
    banner: { js: `/* program-requirements.js — ${GENERATED} */` },
  },
  {
    entryPoints: [path.join(root, 'src/css/program-requirements.css')],
    outfile: path.join(root, 'public/css/program-requirements.css'),
    bundle: true,
    minify: isProd,
    legalComments: 'none',
    banner: { css: `/* program-requirements.css — ${GENERATED} */` },
  },
];

const watch = process.argv.includes('--watch');

if (watch) {
  const contexts = await Promise.all(targets.map((t) => esbuild.context(t)));
  await Promise.all(contexts.map((c) => c.rebuild()));
  await Promise.all(contexts.map((c) => c.watch()));
  console.log('👀 [webflow-assets] watching src/js + src/css → public/{js,css}/* (minified). Ctrl+C to stop.');
} else {
  await Promise.all(targets.map((t) => esbuild.build(t)));
  console.log(`✅ [webflow-assets] built os-course.js, os-course.css, checkout.js, ee-course.js, checkout-cart.js, checkout-cart.css, program-requirements.js, program-requirements.css (${isProd ? 'PROD: minified, logs stripped' : 'DEV/UAT: readable, logs kept'}).`);
}
