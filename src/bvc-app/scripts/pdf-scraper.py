from selenium.webdriver.support.ui import WebDriverWait
from selenium.webdriver.support import expected_conditions as EC
from webdriver_manager.chrome import ChromeDriverManager

class SitecorePDFScraper:
    def __init__(self, headless=False, download_dir=None):
        """Initialize the PDF scraper with Chrome browser automation"""
        self.download_dir = download_dir or os.path.join(os.getcwd(), "public", "data", "course-outlines", "pdf")
        self.setup_browser(headless)
        self.downloaded_count = 0
        self.failed_count = 0
        self.skipped_count = 0
        
    def setup_browser(self, headless=False):
        """Setup Chrome browser with download preferences"""
        print(f"🔧 Setting up Chrome browser...")
        print(f"📁 Download directory: {self.download_dir}")
        
        # Ensure download directory exists
        os.makedirs(self.download_dir, exist_ok=True)
        
        # Chrome options
        chrome_options = Options()
        if headless:
            chrome_options.add_argument("--headless")
        
        # Download preferences
        prefs = {
            "download.default_directory": os.path.abspath(self.download_dir),
            "download.prompt_for_download": False,
            "download.directory_upgrade": True,
            "safebrowsing.enabled": True,
            "profile.default_content_settings.popups": 0,
            "profile.default_content_setting_values.automatic_downloads": 1
        }
        chrome_options.add_experimental_option("prefs", prefs)
        
        # Additional options for better compatibility
        chrome_options.add_argument("--no-sandbox")
        chrome_options.add_argument("--disable-dev-shm-usage")
        chrome_options.add_argument("--disable-blink-features=AutomationControlled")
        chrome_options.add_experimental_option("excludeSwitches", ["enable-automation"])
        chrome_options.add_experimental_option('useAutomationExtension', False)
        
        # Initialize driver
        service = Service(ChromeDriverManager().install())
        self.driver = webdriver.Chrome(service=service, options=chrome_options)
        
        # Execute script to remove webdriver property
        self.driver.execute_script("Object.defineProperty(navigator, 'webdriver', {get: () => undefined})")
        
        print("✅ Browser setup complete")
    
    def manual_login_to_sitecore(self, sitecore_url):
        """Open Sitecore login page and wait for manual login"""
        print(f"🔐 Opening Sitecore for manual login...")
        print(f"🌐 URL: {sitecore_url}")
        
        try:
            # Navigate to Sitecore login
            login_url = f"{sitecore_url}/sitecore/login"
            print(f"📄 Navigating to: {login_url}")
            self.driver.get(login_url)
            
            # Wait for page to load
            time.sleep(3)
            
            print("\n" + "="*60)
            print("🔓 MANUAL LOGIN REQUIRED")
            print("="*60)
            print("1. A Chrome browser window has opened")
            print("2. Please login to Sitecore manually in that window")
            print("3. Navigate around Sitecore to ensure you're logged in")
            print("4. Once you're successfully logged in, come back here")
            print("5. Press ENTER to continue with PDF downloads...")
            print("="*60)
            
            # Wait for user to confirm manual login
            input("Press ENTER when you have completed manual login: ")
            
            # Check current URL to verify login
            current_url = self.driver.current_url
            page_title = self.driver.title
            print(f"\n✅ Continuing with automation...")
            print(f"📋 Current page: {page_title}")
            print(f"🔗 Current URL: {current_url}")
            
            # Basic check if we're in Sitecore
            if "sitecore" in current_url.lower():
                print("✅ Looks like you're logged into Sitecore!")
                return True
            else:
                print("⚠️  Warning: URL doesn't contain 'sitecore' but continuing anyway...")
                return True
                
        except Exception as e:
            print(f"❌ Error during manual login process: {str(e)}")
            return False
    
    def generate_safe_filename(self, course_data):
        """Generate safe filename from course data"""
        academic_year = course_data.get("fields", {}).get("Academic Year", {}).get("value", "Unknown")
        course_code = course_data.get("fields", {}).get("Course Code", {}).get("value", "Unknown")
        course_name = course_data.get("fields", {}).get("CourseName", {}).get("value", "Unknown")
        
        # Create safe filename
        safe_name = f"{academic_year}_{course_code}_{course_name}"
        # Remove invalid characters
        safe_name = "".join(c for c in safe_name if c.isalnum() or c in (' ', '-', '_')).rstrip()
        safe_name = safe_name.replace(' ', '_')[:100]  # Limit length
        
        return f"{safe_name}.pdf"
    
    def download_pdf(self, course_data, base_url):
        """Download a single PDF using browser automation"""
        try:
            file_path_field = course_data.get("fields", {}).get("File Path", {})
            if not file_path_field or not file_path_field.get("value"):
                print(f"  ⚠️  No File Path field found for {course_data.get('name', 'Unknown')}")
                return False
            
            media_path = file_path_field["value"]
            course_name = course_data.get("name", "Unknown")
            
            # Generate the PDF URL (same logic as your working browser URL)
            clean_path = media_path.replace("/sitecore/media library", "")
            if not clean_path.startswith("/"):
                clean_path = "/" + clean_path
            
            pdf_url = f"{base_url}/-/media{clean_path}"
            
            print(f"  📥 Downloading: {course_name}")
            print(f"  🔗 URL: {pdf_url}")
            
            # Generate expected filename
            expected_filename = self.generate_safe_filename(course_data)
            expected_filepath = os.path.join(self.download_dir, expected_filename)
            
            # Check if file already exists
            if os.path.exists(expected_filepath):
                file_size = os.path.getsize(expected_filepath)
                print(f"  ⏭️  Skipping (already exists): {expected_filename} ({file_size} bytes)")
                self.skipped_count += 1
                return True
            
            # Navigate to PDF URL - this should trigger download in browser
            self.driver.get(pdf_url)
            
            # Wait a moment for download to start
            time.sleep(3)
            
            # Check if we got redirected to an error page
            if "<!DOCTYPE html>" in self.driver.page_source[:100]:
                print(f"  ❌ Got HTML page instead of PDF")
                self.failed_count += 1
                return False
            
            # Wait for download to complete (check download directory)
            download_timeout = 30  # seconds
            start_time = time.time()
            
            while time.time() - start_time < download_timeout:
                # Look for downloaded files (Chrome adds .crdownload extension during download)
                downloaded_files = [f for f in os.listdir(self.download_dir) 
                                  if f.endswith('.pdf') and not f.endswith('.crdownload')]
                
                # Find the most recent PDF file
                if downloaded_files:
                    # Sort by modification time, get the newest
                    pdf_files = [(f, os.path.getmtime(os.path.join(self.download_dir, f))) 
                               for f in downloaded_files]
                    newest_file = max(pdf_files, key=lambda x: x[1])[0]
                    newest_path = os.path.join(self.download_dir, newest_file)
                    
                    # Check if this file was just created/modified
                    if time.time() - os.path.getmtime(newest_path) < 10:  # Within last 10 seconds
                        # Rename to expected filename
                        if newest_file != expected_filename:
                            os.rename(newest_path, expected_filepath)
                            print(f"  📁 Renamed: {newest_file} → {expected_filename}")
                        
                        file_size = os.path.getsize(expected_filepath)
                        print(f"  ✅ Downloaded: {expected_filename} ({file_size} bytes)")
                        self.downloaded_count += 1
                        return True
                
                time.sleep(1)
            
            print(f"  ❌ Download timeout - no PDF file appeared in {download_timeout} seconds")
            self.failed_count += 1
            return False
            
        except Exception as e:
            print(f"  ❌ Error downloading {course_data.get('name', 'Unknown')}: {str(e)}")
            self.failed_count += 1
            return False
    
    def load_course_data(self, json_file):
        """Load course data from JSON file"""
        print(f"📖 Loading course data from: {json_file}")
        
        try:
            with open(json_file, 'r', encoding='utf-8') as f:
                data = json.load(f)
            
            print(f"→ Loaded {len(data)} course outlines")
            return data
            
        except Exception as e:
            print(f"❌ Failed to load course data: {str(e)}")
            return []
    
    def filter_current_courses(self, courses):
        """Filter for courses with 'Current' in EffectiveTermEnd"""
        current_courses = []
        
        for course in courses:
            effective_term_end = course.get("fields", {}).get("EffectiveTermEnd", {}).get("value", "")
            if effective_term_end and "Current" in effective_term_end:
                current_courses.append(course)
        
        print(f"📊 Found {len(current_courses)} current courses out of {len(courses)} total")
        return current_courses
    
    def run_scraper(self, courses, base_url, test_mode=False):
        """Main scraper logic"""
        if test_mode:
            courses = courses[:5]
            print(f"🧪 TEST MODE: Processing only {len(courses)} courses")
        
        # Filter courses that have File Path field
        valid_courses = [c for c in courses if c.get("fields", {}).get("File Path", {}).get("value")]
        print(f"📊 Found {len(valid_courses)} courses with File Path field")
        
        total_courses = len(valid_courses)
        
        print(f"🔄 Starting download of {total_courses} PDFs...")
        print(f"📁 Download directory: {self.download_dir}")
        
        for i, course in enumerate(valid_courses, 1):
            print(f"\n📦 Processing {i}/{total_courses}: {course.get('name', 'Unknown')}")
            
            success = self.download_pdf(course, base_url)
            
            # Small delay between downloads
            time.sleep(2)
            
            # Progress update every 10 items
            if i % 10 == 0:
                print(f"   📊 Progress: {i}/{total_courses} - Downloaded: {self.downloaded_count}, Failed: {self.failed_count}, Skipped: {self.skipped_count}")
        
        # Final summary
        print(f"\n🎉 Scraping completed!")
        print(f"📊 Final Statistics:")
        print(f"   • Total courses processed: {total_courses}")
        print(f"   • PDFs downloaded: {self.downloaded_count}")
        print(f"   • PDFs failed: {self.failed_count}")
        print(f"   • PDFs skipped: {self.skipped_count}")
        print(f"   • Success rate: {(self.downloaded_count / total_courses * 100):.1f}%")
    
    def close(self):
        """Clean up browser resources"""
        if self.driver:
            self.driver.quit()
            print("🧹 Browser closed")

